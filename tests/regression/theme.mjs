import assert from 'node:assert/strict';
import { ThemeManager } from '../../resources/js/utils/theme-manager.js';
let stored = null;
let handler;
let attribute;
let events = [];
global.localStorage = { getItem: () => stored, setItem: (_, value) => { stored = value; } };
global.CustomEvent = class { constructor(name, options) { this.name = name; this.detail = options.detail; } };
global.document = { documentElement: { setAttribute: (_, value) => { attribute = value; } }, querySelectorAll: () => [] };
global.window = { matchMedia: () => ({ matches: false, addEventListener: (_, value) => { handler = value; } }), dispatchEvent: event => events.push(event) };
const manager = new ThemeManager();
handler({ matches: true });
assert.equal(attribute, 'dark');
assert.equal(stored, null);
manager.toggleTheme();
assert.equal(attribute, 'light');
assert.equal(stored, 'light');
assert.equal(events.at(-1).detail.theme, 'light');
handler({ matches: true });
assert.equal(attribute, 'light');
localStorage.getItem = () => { throw new Error('Storage disabled'); };
localStorage.setItem = () => { throw new Error('Storage disabled'); };
assert.doesNotThrow(() => new ThemeManager().toggleTheme());
console.log('PASS: theme follows system, persists explicit choices, emits chart updates and survives blocked storage');
