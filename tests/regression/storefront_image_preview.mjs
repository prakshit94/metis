import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const script = fs.readFileSync(new URL('../../public/storefront/product-gallery.js', import.meta.url), 'utf8');
function fixture(count, supported = true) {
    const element = extra => ({listeners: {}, hidden: false, addEventListener(type, callback) { this.listeners[type] = callback; }, fire(type, values = {}) { const event = {target:this, preventDefault() {this.prevented = true;}, ...values}; this.listeners[type]?.(event); return event; }, ...extra});
    const image = element({removeAttribute() {delete this.src;}});
    const counter = element(), previous = element(), next = element(), close = element(), error = element();
    const fields = {'[data-preview-image]':image, '[data-preview-counter]':counter, '[data-preview-previous]':previous, '[data-preview-next]':next, '[data-preview-close]':close, '[data-preview-error]':error};
    const dialog = element({open:false, querySelector: selector => fields[selector], showModal() {this.open=true;}, close() {this.open=false;this.fire('close');}, getBoundingClientRect: () => ({left:10,right:300,top:10,bottom:300})});
    if (!supported) dialog.showModal = undefined;
    const links = Array.from({length:count}, (_,index) => element({href:`https://shop.invalid/images/1/${index+1}`, isConnected:true, focus() {this.focused=true;}, querySelector: () => ({alt:`Product image ${index+1}`})}));
    const classes = new Set();
    vm.runInNewContext(script, {document:{querySelectorAll:()=>links, getElementById:()=>dialog, documentElement:{classList:{add: c=>classes.add(c),remove:c=>classes.delete(c)}}}});
    return {links, dialog, image, counter, previous, next, close, error, classes};
}
const f = fixture(3);
assert.equal(f.links[1].fire('click',{button:0}).prevented,true);
assert.equal(f.dialog.open,true);
assert.equal(f.counter.textContent,'Image 2 of 3');
assert.equal(f.image.alt,'Product image 2');
f.next.fire('click'); assert.equal(f.counter.textContent,'Image 3 of 3');
f.next.fire('click'); assert.equal(f.counter.textContent,'Image 1 of 3');
f.previous.fire('click'); assert.equal(f.counter.textContent,'Image 3 of 3');
f.dialog.fire('keydown',{key:'ArrowLeft'}); assert.equal(f.counter.textContent,'Image 2 of 3');
f.dialog.fire('keydown',{key:'ArrowRight'}); assert.equal(f.counter.textContent,'Image 3 of 3');
f.image.fire('error'); assert.equal(f.error.hidden,false); assert.match(f.image.src,/product-placeholder/);
f.previous.fire('click'); assert.equal(f.error.hidden,true);
f.dialog.fire('click',{clientX:100,clientY:100}); assert.equal(f.dialog.open,true);
f.dialog.fire('click',{clientX:0,clientY:0}); assert.equal(f.dialog.open,false);
assert.equal(f.links[1].focused,true);
assert.equal(f.classes.size,0);
assert.equal(f.image.src,undefined);
assert.equal(f.links[0].fire('click',{button:0,ctrlKey:true}).prevented,undefined);
assert.equal(f.dialog.open,false);
f.links[0].fire('click',{button:0}); f.close.fire('click'); assert.equal(f.dialog.open,false);
const one=fixture(1); one.links[0].fire('click',{button:0});
assert.equal(one.previous.hidden,true); assert.equal(one.next.hidden,true); assert.equal(one.counter.textContent,'Image 1 of 1');
one.dialog.fire('keydown',{key:'ArrowRight'}); assert.equal(one.counter.textContent,'Image 1 of 1');
const fallback=fixture(1,false); assert.equal(fallback.links[0].fire('click',{button:0}).prevented,undefined);
fixture(0);
console.log('PASS: clicked image, next/previous wrap, arrow keys, single/empty galleries, fallback links, errors, backdrop closing, focus and scroll restoration');
