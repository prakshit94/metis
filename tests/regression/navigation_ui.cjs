// No network or application writes. Test the shared sidebar's presentation state.
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const classes = () => { const set = new Set(); return {contains:k=>set.has(k), add:k=>set.add(k), remove:k=>set.delete(k), toggle:(k,on)=>on?set.add(k):set.delete(k)}; };
const context = {MOBILE_BREAKPOINT_PX:992, RESIZE_DEBOUNCE_MS:100, window:{innerWidth:375}, document:{body:{style:{overflow:'auto'}},activeElement:null},localStorage:{getItem:()=> 'false'}};
vm.createContext(context);
vm.runInContext(fs.readFileSync('resources/js/components/sidebar.js','utf8').replace(/^import .*;$/gm,'').replace('export class SidebarManager','globalThis.SidebarManager = class SidebarManager'),context);
const ui = Object.create(context.SidebarManager.prototype);
const attributes = {};
ui.sidebar = {classList:classes(),setAttribute:(k,v)=>attributes[k]=v,contains:()=>false};
ui.wrapper = {classList:classes()}; ui.backdrop = {classList:classes()};
ui.toggleButton = {classList:classes(),setAttribute:(k,v)=>attributes[k]=v};
ui.wasMobile = true; ui.previousBodyOverflow = null;
ui.openMobile();
assert.equal(attributes['aria-expanded'],'true'); assert.equal(ui.sidebar.inert,false);
assert.equal(context.document.body.style.overflow,'hidden');
ui.handleResize(); assert.equal(ui.sidebar.classList.contains('show'),true,'Same-breakpoint resize preserves open sidebar');
ui.closeMobile(); assert.equal(ui.sidebar.inert,true); assert.equal(attributes['aria-label'],'Show sidebar');
assert.equal(context.document.body.style.overflow,'auto','Original scroll style is restored');
ui.openMobile(); context.window.innerWidth=1440; ui.handleResize();
assert.equal(ui.sidebar.classList.contains('show'),false); assert.equal(attributes['aria-expanded'],'true');
assert.equal(context.document.body.style.overflow,'auto');
console.log('PASS: sidebar visibility, inert state, accessible labels, resize and scroll restoration.');
