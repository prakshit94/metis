// Shared display logic only; no server or real file mutations.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const meta = {content:''};
let images = [], signals=[];
const context = {URL, window:{location:{origin:'http://127.0.0.1:8000',hostname:'127.0.0.1'}},
 document:{querySelector:()=>meta,querySelectorAll:()=>images}, localStorage:{setItem:(...args)=>signals.push(args)}};
vm.createContext(context);
vm.runInContext(fs.readFileSync('resources/js/utils/profile-images.js','utf8').replace(/^export /gm,''),context);
const image = (photo,gender,id) => ({dataset:{profilePhoto:photo,profileGender:gender,profileUserId:id},style:{},src:'',getAttribute(){return this.src;},setAttribute(name,value){this[name]=value;}});
assert.equal(context.userPhotoUrl({gender:'Male'}),'/assets/images/default_male.png');
assert.equal(context.userPhotoUrl({gender:'Female'}),'/assets/images/default_female.png');
assert.equal(context.normalizePhotoUrl('http://localhost:8000/storage/users/photos/a.jpg'),'/storage/users/photos/a.jpg');
assert.equal(context.normalizePhotoUrl('public\\storage\\users\\photos\\a.jpg'),'/storage/users/photos/a.jpg');
assert.equal(context.normalizePhotoUrl('https://images.example.com/avatar.jpg?q=1'),'https://images.example.com/avatar.jpg?q=1');
assert.equal(context.normalizePhotoUrl('javascript:alert(1)'),'');
assert.equal(context.normalizePhotoUrl('blob:preview'),'blob:preview');
images=[image('', 'Male','1'),image('users/photos/personal.jpg','Female','2')];
context.setDefaultAvatar('/api/files/preview?f=avatar.png');
assert.equal(images[0].src,'/api/files/preview?f=avatar.png');
assert.equal(images[1].src,'/storage/users/photos/personal.jpg');
assert.equal(context.userPhotoUrl({photo:'/assets/images/default_female.png',gender:'Female'}),'/api/files/preview?f=avatar.png');
const broken=image('missing.jpg','Male','3');broken.src='/storage/missing.jpg';
context.handlePhotoError({target:broken},{gender:'Male'});assert.equal(broken.src,meta.content);
context.handlePhotoError({target:broken},{gender:'Male'});assert.equal(broken.src,'/assets/images/default_male.png');
context.handlePhotoError({target:broken},{gender:'Male'});assert.equal(broken.src,'/assets/images/default_avatar.jpeg');
context.handlePhotoError({target:broken},{gender:'Male'});assert.equal(broken.style.visibility,'hidden','fallback terminates if all images fail');
context.setDefaultAvatar('/api/files/preview?f=another.png');assert.equal(images[0].src,meta.content);
context.updateUserPhoto({id:1,photo:'users/photos/new.jpg'});assert.equal(images[0].src,'/storage/users/photos/new.jpg');
context.setDefaultAvatar('');assert.equal(images[0].src,'/storage/users/photos/new.jpg','changing default preserves the new personal photo');
assert.equal(images[1].src,'/storage/users/photos/personal.jpg');
assert.equal(context.defaultUserPhoto({gender:'Female'}),'/assets/images/default_female.png');
assert.ok(signals.length>=3);
console.log('PASS: configured defaults, personal-photo priority, legacy placeholders, URL normalization, blob previews, bounded broken-image fallback, live updates and deletion reset.');
