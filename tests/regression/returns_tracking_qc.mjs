import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const factories = {};
let download;
const context = {
  Alpine: {data(name, factory) { factories[name] = factory; }},
  document: {addEventListener(event, callback) { callback(); }, createElement() { return {click() {}}; }, body: {appendChild() {}, removeChild() {}}},
  Blob, URL: {createObjectURL(blob) { download = blob; return 'blob:test'; }, revokeObjectURL() {}},
  Modal: {}, Swal: {},
};
vm.createContext(context);
vm.runInContext(fs.readFileSync('resources/js/components/returns.js','utf8').replace(/^import .*;\n/gm,''), context);
const table = factories.returnsTable();
table.downloadBulkQcTemplate();
assert.equal(await download.text(), 'order_id\n');
table.qcIdentifier = 'tracking_id'; table.downloadBulkQcTemplate();
assert.equal(await download.text(), 'tracking_id\n');
console.log('PASS: returns templates support both order ID and tracking ID headers');

context.document.getElementById = () => null;
context.document.querySelector = () => ({content:'csrf'});
context.console = console;
table.$nextTick = callback => callback();
const ret = (id, status) => ({id, status, return_no:'RMA-'+id, items:[{id:id*10,product_id:1,requested_qty:2,product:{id:1,name:'Product',sku:'SKU'}}]});
table.importReviewData = {returns:[ret(1,'approved'),ret(2,'pending'),ret(3,'pending')], preview:[1,2,3].map(id => ({return_id:id,sku:'SKU',received_qty:2,restocked_qty:2,damaged_qty:0}))};
table.bypassReturnIds = ['2'];
table.continueImportedQc();
assert.deepEqual(Array.from(table.selectedReturnsForBulk, ret => ret.id), [1,2]);
assert.equal(table.bulkQcItems[0].received_qty,4,'unchecked pending return must not contribute QC quantities');
const submitted=[];
context.fetch = async (url, options) => { submitted.push({url,body:JSON.parse(options.body)}); return {ok:true,text:async () => '{"success":true}'}; };
table.closeBulkQcModal = () => {};
table.loadReturns = () => {};
await table.submitBulkQc();
assert.equal(submitted.length,2);
assert.equal(submitted[0].body.bypass_approval,undefined);
assert.equal(submitted[1].body.bypass_approval,true);
assert.ok(submitted.every(row => !row.url.includes('/3/')));
table.returns=[ret(2,'pending')]; table.selectedReturns=['2'];
table.openBulkQcModal();
assert.equal(table.bypassReturnIds.length,0,'new selection must not inherit old bypass consent');
assert.equal(table.pendingImportedReturns.length,1);
console.log('PASS: pending QC excludes unchecked returns, flags only checked returns, and resets bypass selection');

const mixed=factories.returnsTable();
mixed.$nextTick=callback=>callback();
mixed.importReviewData={returns:[ret(1,'approved'),ret(2,'approved'),ret(3,'pending'),ret(4,'pending')],preview:[1,2,3,4].map(id=>({return_id:String(id),return_item_id:id*10,identifier_lookup:true,product_id:1,sku:'SKU',received_qty:2,restocked_qty:2,damaged_qty:0}))};
mixed.importReviewData.preview.push({...mixed.importReviewData.preview[0]});
mixed.bypassReturnIds=['3'];
mixed.continueImportedQc();
assert.deepEqual(Array.from(mixed.selectedReturnsForBulk,ret=>ret.id),[1,2,3],'all approved and only checked pending returns reach restock');
assert.equal(mixed.bulkQcItems[0].requested_qty,6);
assert.equal(mixed.bulkQcItems[0].received_qty,6,'repeated references to the same return item cannot inflate quantities');
assert.equal(mixed.bulkQcItems[0].items.length,3,'aggregation retains every selected approved return item');
const view=fs.readFileSync('resources/views/orders/returns/index.blade.php','utf8');
assert.match(view,/x-for="ret in \(importReviewData\?\.returns \|\| \[\]\)"/);
assert.match(view,/Included returns/);
console.log('PASS: mixed approved/pending review lists all returns and deduplicates identifier quantities');

mixed.toggleAllPendingBypass(true);
assert.deepEqual(Array.from(mixed.bypassReturnIds), ['3','4']);
assert.equal(mixed.allPendingBypassSelected,true);
mixed.bypassReturnIds=['3'];
assert.equal(mixed.pendingBypassSelectionCount,1);
assert.equal(mixed.allPendingBypassSelected,false);
mixed.toggleAllPendingBypass(false);
assert.equal(mixed.bypassReturnIds.length,0);
mixed.isSubmitting=true; mixed.toggleAllPendingBypass(true);
assert.equal(mixed.bypassReturnIds.length,0);
mixed.isSubmitting=false; mixed.importReviewData=null;
assert.equal(mixed.allPendingBypassSelected,false);
console.log('PASS: select-all affects only pending returns, supports partial selection and respects submission lock');

const pages=factories.returnsTable();
pages.$nextTick=callback=>callback();
pages.returns=[ret(11,'approved')]; pages.toggleReturn(pages.returns[0],true);
pages.returns=[ret(22,'approved')]; pages.toggleReturn(pages.returns[0],true);
pages.openBulkQcModal();
assert.deepEqual(Array.from(pages.selectedReturnsForBulk,row=>row.id),[11,22],'QC includes selections made on different pages/search results');
assert.equal(pages.bulkQcItems[0].requested_qty,4);
pages.toggleAll(false);
assert.deepEqual(Array.from(pages.selectedReturns),['11'],'unchecking current page preserves selections on other pages');
pages.returns=[];
assert.equal(pages.bulkAvailableActions.qc,true,'actions remain available for selections outside current search results');
pages.clearSelection();
assert.equal(Object.keys(pages.selectedReturnsMap).length,0);
assert.equal(pages.selectedReturnRecords.length,0);
pages.returns=[ret(33,'pending')]; pages.toggleReturn(pages.returns[0],true);
pages.returns=[ret(44,'approved')]; pages.toggleReturn(pages.returns[0],true);
pages.openBulkQcModal();
assert.equal(pages.pendingImportedReturns[0].id,33,'off-page pending selections enter bypass review');
assert.equal(pages.importReviewData.returns.length,2);
context.URLSearchParams=URLSearchParams;
const responses=[];
context.fetch=()=>new Promise(resolve=>responses.push(resolve));
pages.currentPage=1; const older=pages.loadReturns();
pages.currentPage=2; const newer=pages.loadReturns();
responses[1]({ok:true,text:async()=>JSON.stringify({returns:{data:[ret(44,'received')],current_page:2,last_page:2,total:2}})});
await newer;
responses[0]({ok:true,text:async()=>JSON.stringify({returns:{data:[ret(99,'approved')],current_page:1,last_page:2,total:2}})});
await older;
assert.equal(pages.returns[0].id,44,'late search/page responses cannot overwrite current results');
assert.equal(pages.selectedReturnsMap['44'].status,'received','reloaded selected rows refresh their cached data');
assert.equal(pages.selectedReturnRecords.length,2);
console.log('PASS: cross-page QC selection, page-only deselection, hidden selections, cache refresh and search response ordering');
